CREATE OR REPLACE FUNCTION public.create_session_with_athletes(
  p_session jsonb,
  p_athlete_ids integer[],
  p_idempotency_key text DEFAULT NULL
) RETURNS jsonb
LANGUAGE plpgsql SECURITY DEFINER SET search_path TO 'public' AS $$
DECLARE
  v_user_id integer := public.get_my_user_id();
  v_club_id integer := public.get_my_club_id();
  v_role text := public.get_my_role();
  v_my_athlete_id integer := public.get_my_athlete_id();
  v_cached jsonb;
  v_session_id integer;
  v_result jsonb;
  v_target_group text := CASE WHEN v_role IN ('head_coach','coach') THEN nullif(p_session->>'targetGroup','') ELSE NULL END;
BEGIN
  IF v_user_id IS NULL OR v_role NOT IN ('head_coach','coach','athlete') THEN RAISE EXCEPTION 'Action non autorisee.'; END IF;
  IF v_role='athlete' AND NOT (v_my_athlete_id=ANY(p_athlete_ids)) THEN RAISE EXCEPTION 'Ta propre affectation est obligatoire.'; END IF;
  IF p_idempotency_key IS NOT NULL THEN
    PERFORM pg_advisory_xact_lock(hashtextextended('create_session_with_athletes:'||p_idempotency_key,0));
    SELECT result INTO v_cached FROM public.rpc_idempotency
    WHERE fn_name='create_session_with_athletes' AND idempotency_key=p_idempotency_key AND actor_user_id=v_user_id;
    IF v_cached IS NOT NULL THEN RETURN v_cached; END IF;
  END IF;
  PERFORM public._assert_session_write(p_session,p_athlete_ids,NULL);
  INSERT INTO public.sessions(
    club_id,week,day,session_date,time,type,category,title,training_focus,
    description,instructions,duration_minutes,load_weight,pdf_url,created_by,
    source_kind,target_group
  ) VALUES (
    v_club_id,nullif(p_session->>'week','')::integer,nullif(p_session->>'day',''),
    (p_session->>'sessionDate')::date,p_session->>'time',nullif(p_session->>'type',''),
    nullif(p_session->>'category',''),btrim(p_session->>'title'),nullif(p_session->>'trainingFocus',''),
    nullif(p_session->>'description',''),nullif(p_session->>'instructions',''),
    (p_session->>'durationMinutes')::integer,coalesce(nullif(p_session->>'loadWeight','')::numeric,1.0),
    nullif(p_session->>'pdfUrl',''),v_user_id,
    CASE WHEN v_target_group IS NULL THEN 'individual' ELSE 'group' END,v_target_group
  ) RETURNING id INTO v_session_id;
  INSERT INTO public.session_athletes(session_id,athlete_id,status)
  SELECT v_session_id,athlete_id,NULL FROM unnest(p_athlete_ids) athlete_id;
  v_result:=jsonb_build_object('sessionId',v_session_id);
  IF p_idempotency_key IS NOT NULL THEN
    INSERT INTO public.rpc_idempotency(fn_name,idempotency_key,actor_user_id,result)
    VALUES('create_session_with_athletes',p_idempotency_key,v_user_id,v_result)
    ON CONFLICT(fn_name,idempotency_key) DO NOTHING;
  END IF;
  RETURN v_result;
END;
$$;

CREATE OR REPLACE FUNCTION public.update_session_with_athletes(
  p_session_id integer,
  p_session jsonb,
  p_athlete_ids integer[]
) RETURNS jsonb
LANGUAGE plpgsql SECURITY DEFINER SET search_path TO 'public' AS $$
DECLARE
  v_user_id integer:=public.get_my_user_id();
  v_club_id integer:=public.get_my_club_id();
  v_role text:=public.get_my_role();
  v_existing public.sessions%ROWTYPE;
  v_target_group text;
BEGIN
  SELECT * INTO v_existing FROM public.sessions WHERE id=p_session_id FOR UPDATE;
  IF NOT FOUND OR v_existing.club_id<>v_club_id THEN RAISE EXCEPTION 'Seance introuvable.'; END IF;
  IF v_role NOT IN ('head_coach','coach') AND NOT (v_role='athlete' AND v_existing.created_by=v_user_id) THEN RAISE EXCEPTION 'Action non autorisee.'; END IF;
  IF v_role='athlete' AND NOT (public.get_my_athlete_id()=ANY(p_athlete_ids)) THEN RAISE EXCEPTION 'Ta propre affectation est obligatoire.'; END IF;
  PERFORM public._assert_session_write(p_session,p_athlete_ids,p_session_id);
  v_target_group:=CASE WHEN v_role IN ('head_coach','coach') AND p_session?'targetGroup'
    THEN nullif(p_session->>'targetGroup','') ELSE v_existing.target_group END;
  UPDATE public.sessions SET
    week=nullif(p_session->>'week','')::integer,day=nullif(p_session->>'day',''),
    session_date=(p_session->>'sessionDate')::date,time=p_session->>'time',
    type=nullif(p_session->>'type',''),category=nullif(p_session->>'category',''),
    title=btrim(p_session->>'title'),training_focus=nullif(p_session->>'trainingFocus',''),
    description=nullif(p_session->>'description',''),instructions=nullif(p_session->>'instructions',''),
    duration_minutes=(p_session->>'durationMinutes')::integer,
    load_weight=coalesce(nullif(p_session->>'loadWeight','')::numeric,load_weight),
    pdf_url=CASE WHEN p_session?'pdfUrl' THEN nullif(p_session->>'pdfUrl','') ELSE pdf_url END,
    target_group=v_target_group,
    source_kind=CASE WHEN series_id IS NULL AND source_kind IN ('individual','group')
      THEN CASE WHEN v_target_group IS NULL THEN 'individual' ELSE 'group' END ELSE source_kind END,
    updated_by=CASE WHEN v_role IN ('head_coach','coach') THEN v_user_id ELSE updated_by END,
    updated_at=now()
  WHERE id=p_session_id;
  DELETE FROM public.session_athletes WHERE session_id=p_session_id AND NOT (athlete_id=ANY(p_athlete_ids));
  INSERT INTO public.session_athletes(session_id,athlete_id,status)
  SELECT p_session_id,athlete_id,NULL FROM unnest(p_athlete_ids) athlete_id ON CONFLICT(session_id,athlete_id) DO NOTHING;
  RETURN jsonb_build_object('sessionId',p_session_id);
END;
$$;

