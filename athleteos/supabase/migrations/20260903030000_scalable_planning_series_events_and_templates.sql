CREATE OR REPLACE FUNCTION public.upsert_planning_event_with_athletes(
  p_event_id bigint,
  p_event jsonb,
  p_athlete_ids integer[]
) RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO 'public'
AS $$
DECLARE v_event_id bigint := p_event_id; v_club_id integer := public.get_my_club_id();
BEGIN
  IF public.get_my_role() NOT IN ('head_coach', 'coach') THEN RAISE EXCEPTION 'Action non autorisee.'; END IF;
  IF cardinality(coalesce(p_athlete_ids, ARRAY[]::integer[])) = 0 THEN RAISE EXCEPTION 'Selectionne au moins un athlete.'; END IF;
  IF EXISTS (SELECT 1 FROM unnest(p_athlete_ids) athlete_id WHERE NOT EXISTS (
    SELECT 1 FROM public.athletes athlete WHERE athlete.id = athlete_id AND athlete.club_id = v_club_id
  )) THEN RAISE EXCEPTION 'Un athlete selectionne n appartient pas au club.'; END IF;

  IF v_event_id IS NULL THEN
    INSERT INTO public.planning_events (club_id, kind, name, starts_on, ends_on, time, location, description, notes, custom_label, target_group, created_by)
    VALUES (v_club_id, p_event->>'kind', btrim(p_event->>'name'), (p_event->>'startsOn')::date,
      coalesce(nullif(p_event->>'endsOn','')::date, (p_event->>'startsOn')::date), nullif(p_event->>'time',''),
      nullif(p_event->>'location',''), nullif(p_event->>'description',''), nullif(p_event->>'notes',''),
      nullif(p_event->>'customLabel',''), nullif(p_event->>'targetGroup',''), public.get_my_user_id())
    RETURNING id INTO v_event_id;
  ELSE
    UPDATE public.planning_events SET kind = p_event->>'kind', name = btrim(p_event->>'name'),
      starts_on = (p_event->>'startsOn')::date,
      ends_on = coalesce(nullif(p_event->>'endsOn','')::date, (p_event->>'startsOn')::date),
      time = nullif(p_event->>'time',''), location = nullif(p_event->>'location',''),
      description = nullif(p_event->>'description',''), notes = nullif(p_event->>'notes',''),
      custom_label = nullif(p_event->>'customLabel',''), target_group = nullif(p_event->>'targetGroup',''),
      updated_by = public.get_my_user_id(), updated_at = now()
    WHERE id = v_event_id AND club_id = v_club_id;
    IF NOT FOUND THEN RAISE EXCEPTION 'Evenement introuvable.'; END IF;
  END IF;
  DELETE FROM public.planning_event_athletes WHERE event_id = v_event_id AND NOT (athlete_id = ANY(p_athlete_ids));
  INSERT INTO public.planning_event_athletes (event_id, athlete_id)
  SELECT v_event_id, athlete_id FROM unnest(p_athlete_ids) athlete_id
  ON CONFLICT (event_id, athlete_id) DO NOTHING;
  RETURN jsonb_build_object('eventId', v_event_id);
END;
$$;

