CREATE OR REPLACE FUNCTION public.update_competition_with_athletes(
  p_competition_id integer,
  p_name text,
  p_date date,
  p_location text,
  p_type text,
  p_notes text,
  p_athlete_entries jsonb
) RETURNS jsonb
LANGUAGE plpgsql SECURITY DEFINER SET search_path TO 'public' AS $$
DECLARE v_club_id integer := public.get_my_club_id();
BEGIN
  IF public.get_my_role() NOT IN ('head_coach','coach') THEN RAISE EXCEPTION 'Action non autorisee.'; END IF;
  IF nullif(btrim(p_name),'') IS NULL OR p_date IS NULL THEN RAISE EXCEPTION 'Nom et date requis.'; END IF;
  IF EXISTS (
    SELECT 1 FROM jsonb_to_recordset(coalesce(p_athlete_entries,'[]'::jsonb)) AS entry("athleteId" integer, "plannedEvent" text)
    WHERE NOT EXISTS (SELECT 1 FROM public.athletes athlete WHERE athlete.id = entry."athleteId" AND athlete.club_id = v_club_id)
  ) THEN RAISE EXCEPTION 'Un athlete selectionne n appartient pas au club.'; END IF;
  UPDATE public.competitions SET name=btrim(p_name), date=p_date, location=nullif(p_location,''), type=nullif(p_type,''), notes=nullif(p_notes,'')
  WHERE id=p_competition_id AND club_id=v_club_id;
  IF NOT FOUND THEN RAISE EXCEPTION 'Competition introuvable.'; END IF;
  DELETE FROM public.competition_athletes WHERE competition_id=p_competition_id AND athlete_id NOT IN (
    SELECT entry."athleteId" FROM jsonb_to_recordset(coalesce(p_athlete_entries,'[]'::jsonb)) AS entry("athleteId" integer, "plannedEvent" text)
  );
  INSERT INTO public.competition_athletes (competition_id, athlete_id, planned_event)
  SELECT p_competition_id, entry."athleteId", nullif(entry."plannedEvent",'')
  FROM jsonb_to_recordset(coalesce(p_athlete_entries,'[]'::jsonb)) AS entry("athleteId" integer, "plannedEvent" text)
  ON CONFLICT (competition_id, athlete_id) DO UPDATE SET planned_event=EXCLUDED.planned_event;
  RETURN jsonb_build_object('competitionId',p_competition_id);
END;
$$;

