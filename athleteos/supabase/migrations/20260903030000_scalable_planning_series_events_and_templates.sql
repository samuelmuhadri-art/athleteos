CREATE OR REPLACE FUNCTION public._series_dates(
  p_starts_on date,
  p_ends_on date,
  p_occurrence_count integer,
  p_interval_weeks integer,
  p_weekdays smallint[]
) RETURNS TABLE(occurrence_date date)
LANGUAGE sql
IMMUTABLE
SET search_path TO 'public'
AS $$
  SELECT candidate::date
  FROM generate_series(
    p_starts_on::timestamp,
    coalesce(p_ends_on, p_starts_on + 730)::timestamp,
    interval '1 day'
  ) candidate
  WHERE extract(isodow FROM candidate)::smallint = ANY(p_weekdays)
    AND ((candidate::date - p_starts_on) / 7) % p_interval_weeks = 0
  ORDER BY candidate
  LIMIT coalesce(p_occurrence_count, 104)
$$;

CREATE OR REPLACE FUNCTION public.create_session_series_with_occurrences(
  p_series jsonb,
  p_athlete_ids integer[],
  p_idempotency_key text DEFAULT NULL
) RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO 'public'
AS $$
DECLARE
  v_user_id integer := public.get_my_user_id();
  v_club_id integer := public.get_my_club_id();
  v_series_id bigint;
  v_date date;
  v_session_id integer;
  v_count integer := 0;
  v_weekdays smallint[];
  v_interval integer := coalesce(nullif(p_series->>'intervalWeeks', '')::integer, 1);
  v_starts_on date := nullif(p_series->>'startsOn', '')::date;
  v_ends_on date := nullif(p_series->>'endsOn', '')::date;
  v_occurrence_count integer := nullif(p_series->>'occurrenceCount', '')::integer;
  v_source text := CASE WHEN nullif(p_series->>'targetGroup', '') IS NULL THEN 'series' ELSE 'group_series' END;
  v_cached jsonb;
  v_result jsonb;
BEGIN
  IF v_user_id IS NULL OR public.get_my_role() NOT IN ('head_coach', 'coach') THEN
    RAISE EXCEPTION 'Action non autorisee.';
  END IF;
  IF p_idempotency_key IS NOT NULL THEN
    PERFORM pg_advisory_xact_lock(hashtextextended('create_session_series:' || p_idempotency_key, 0));
    SELECT result INTO v_cached FROM public.rpc_idempotency
    WHERE fn_name = 'create_session_series_with_occurrences'
      AND idempotency_key = p_idempotency_key AND actor_user_id = v_user_id;
    IF v_cached IS NOT NULL THEN RETURN v_cached; END IF;
  END IF;

  SELECT array_agg(DISTINCT value::smallint ORDER BY value::smallint)
  INTO v_weekdays
  FROM jsonb_array_elements_text(coalesce(p_series->'weekdays', '[]'::jsonb)) value;
  IF v_starts_on IS NULL OR cardinality(coalesce(v_weekdays, ARRAY[]::smallint[])) = 0 THEN
    RAISE EXCEPTION 'Date de debut et jour de recurrence requis.';
  END IF;
  IF v_ends_on IS NULL AND v_occurrence_count IS NULL THEN
    RAISE EXCEPTION 'Indique une date de fin ou un nombre de repetitions.';
  END IF;
  IF v_ends_on IS NOT NULL AND v_ends_on > v_starts_on + 730 THEN
    RAISE EXCEPTION 'Une serie ne peut pas depasser deux ans.';
  END IF;

  INSERT INTO public.session_series (
    club_id, title, time, type, category, training_focus, duration_minutes,
    description, instructions, interval_weeks, weekdays, starts_on, ends_on,
    occurrence_count, target_group, created_by
  ) VALUES (
    v_club_id, btrim(p_series->>'title'), p_series->>'time', nullif(p_series->>'type', ''),
    nullif(p_series->>'category', ''), nullif(p_series->>'trainingFocus', ''),
    (p_series->>'durationMinutes')::integer, nullif(p_series->>'description', ''),
    nullif(p_series->>'instructions', ''), v_interval, v_weekdays, v_starts_on,
    v_ends_on, v_occurrence_count, nullif(p_series->>'targetGroup', ''), v_user_id
  ) RETURNING id INTO v_series_id;

  FOR v_date IN SELECT occurrence_date FROM public._series_dates(
    v_starts_on, v_ends_on, v_occurrence_count, v_interval, v_weekdays
  ) LOOP
    PERFORM public._assert_session_write(
      jsonb_build_object(
        'title', p_series->>'title', 'sessionDate', v_date, 'time', p_series->>'time',
        'durationMinutes', p_series->>'durationMinutes'
      ), p_athlete_ids, NULL
    );
    INSERT INTO public.sessions (
      club_id, week, day, session_date, time, type, category, title,
      training_focus, description, instructions, duration_minutes, load_weight,
      created_by, series_id, series_original_date, source_kind, target_group
    ) VALUES (
      v_club_id, extract(week FROM v_date)::integer,
      CASE extract(isodow FROM v_date)::integer
        WHEN 1 THEN 'Lundi' WHEN 2 THEN 'Mardi' WHEN 3 THEN 'Mercredi'
        WHEN 4 THEN 'Jeudi' WHEN 5 THEN 'Vendredi' WHEN 6 THEN 'Samedi' ELSE 'Dimanche' END,
      v_date, p_series->>'time', nullif(p_series->>'type', ''), nullif(p_series->>'category', ''),
      btrim(p_series->>'title'), nullif(p_series->>'trainingFocus', ''),
      nullif(p_series->>'description', ''), nullif(p_series->>'instructions', ''),
      (p_series->>'durationMinutes')::integer,
      coalesce(nullif(p_series->>'loadWeight', '')::numeric, 1.0), v_user_id,
      v_series_id, v_date, v_source, nullif(p_series->>'targetGroup', '')
    ) RETURNING id INTO v_session_id;

    INSERT INTO public.session_athletes (session_id, athlete_id, status)
    SELECT v_session_id, athlete_id, NULL FROM unnest(p_athlete_ids) athlete_id;
    v_count := v_count + 1;
  END LOOP;

  IF v_count = 0 THEN RAISE EXCEPTION 'Aucune occurrence generee.'; END IF;
  v_result := jsonb_build_object('seriesId', v_series_id, 'occurrenceCount', v_count);
  IF p_idempotency_key IS NOT NULL THEN
    INSERT INTO public.rpc_idempotency (fn_name, idempotency_key, actor_user_id, result)
    VALUES ('create_session_series_with_occurrences', p_idempotency_key, v_user_id, v_result)
    ON CONFLICT (fn_name, idempotency_key) DO NOTHING;
  END IF;
  RETURN v_result;
END;
$$;

CREATE OR REPLACE FUNCTION public.update_recurring_session(
  p_session_id integer,
  p_scope text,
  p_patch jsonb,
  p_athlete_ids integer[]
) RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO 'public'
AS $$
DECLARE
  v_origin public.sessions%ROWTYPE;
  v_target public.sessions%ROWTYPE;
  v_form jsonb;
  v_count integer := 0;
BEGIN
  IF p_scope NOT IN ('single', 'future', 'all') THEN RAISE EXCEPTION 'Portee invalide.'; END IF;
  SELECT * INTO v_origin FROM public.sessions WHERE id = p_session_id;
  IF NOT FOUND OR v_origin.club_id <> public.get_my_club_id() THEN RAISE EXCEPTION 'Seance introuvable.'; END IF;
  IF public.get_my_role() NOT IN ('head_coach', 'coach') THEN RAISE EXCEPTION 'Action non autorisee.'; END IF;

  FOR v_target IN
    SELECT session.* FROM public.sessions session
    WHERE session.club_id = v_origin.club_id
      AND (
        (p_scope = 'single' AND session.id = v_origin.id)
        OR (p_scope = 'future' AND session.series_id = v_origin.series_id AND session.session_date >= v_origin.session_date)
        OR (p_scope = 'all' AND session.series_id = v_origin.series_id AND session.session_date >= current_date)
      )
    ORDER BY session.session_date
  LOOP
    v_form := jsonb_build_object(
      'title', v_target.title, 'type', v_target.type, 'category', v_target.category,
      'trainingFocus', v_target.training_focus, 'sessionDate', v_target.session_date,
      'time', v_target.time, 'durationMinutes', v_target.duration_minutes,
      'description', v_target.description, 'instructions', v_target.instructions,
      'loadWeight', v_target.load_weight, 'pdfUrl', v_target.pdf_url,
      'week', v_target.week, 'day', v_target.day
    ) || CASE
      WHEN p_scope = 'single' THEN p_patch
      ELSE p_patch - ARRAY['sessionDate','week','day']
    END;
    PERFORM public.update_session_with_athletes(v_target.id, v_form, p_athlete_ids);
    UPDATE public.sessions SET updated_at = now(), updated_by = public.get_my_user_id(),
      source_kind = CASE WHEN p_scope = 'single' THEN 'exception' ELSE source_kind END
    WHERE id = v_target.id;
    v_count := v_count + 1;
  END LOOP;

  IF v_origin.series_id IS NOT NULL AND p_scope <> 'single' THEN
    UPDATE public.session_series SET
      title = coalesce(nullif(p_patch->>'title', ''), title),
      time = coalesce(nullif(p_patch->>'time', ''), time),
      type = CASE WHEN p_patch ? 'type' THEN nullif(p_patch->>'type', '') ELSE type END,
      category = CASE WHEN p_patch ? 'category' THEN nullif(p_patch->>'category', '') ELSE category END,
      training_focus = CASE WHEN p_patch ? 'trainingFocus' THEN nullif(p_patch->>'trainingFocus', '') ELSE training_focus END,
      duration_minutes = coalesce(nullif(p_patch->>'durationMinutes', '')::integer, duration_minutes),
      description = CASE WHEN p_patch ? 'description' THEN nullif(p_patch->>'description', '') ELSE description END,
      instructions = CASE WHEN p_patch ? 'instructions' THEN nullif(p_patch->>'instructions', '') ELSE instructions END,
      updated_at = now(), updated_by = public.get_my_user_id()
    WHERE id = v_origin.series_id;
  END IF;
  RETURN jsonb_build_object('updatedCount', v_count, 'scope', p_scope);
END;
$$;

CREATE OR REPLACE FUNCTION public.delete_recurring_session(p_session_id integer, p_scope text)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO 'public'
AS $$
DECLARE
  v_origin public.sessions%ROWTYPE;
  v_deleted integer := 0;
  v_preserved integer := 0;
BEGIN
  IF p_scope NOT IN ('single', 'future', 'all') THEN RAISE EXCEPTION 'Portee invalide.'; END IF;
  SELECT * INTO v_origin FROM public.sessions WHERE id = p_session_id FOR UPDATE;
  IF NOT FOUND OR v_origin.club_id <> public.get_my_club_id() THEN RAISE EXCEPTION 'Seance introuvable.'; END IF;
  IF public.get_my_role() NOT IN ('head_coach', 'coach') THEN RAISE EXCEPTION 'Action non autorisee.'; END IF;

  IF p_scope = 'single' OR v_origin.series_id IS NULL THEN
    PERFORM public.delete_session_transactional(p_session_id);
    RETURN jsonb_build_object('deletedCount', 1, 'preservedCount', 0, 'scope', 'single');
  END IF;

  SELECT count(*) INTO v_preserved FROM public.sessions session
  WHERE session.series_id = v_origin.series_id
    AND session.session_date < CASE WHEN p_scope = 'future' THEN v_origin.session_date ELSE current_date END;

  DELETE FROM public.sessions session
  WHERE session.series_id = v_origin.series_id
    AND session.session_date >= CASE WHEN p_scope = 'future' THEN v_origin.session_date ELSE current_date END
    AND NOT EXISTS (
      SELECT 1 FROM public.session_athletes assignment
      WHERE assignment.session_id = session.id
        AND (assignment.rpe IS NOT NULL OR assignment.comment IS NOT NULL OR assignment.feedback_submitted_at IS NOT NULL)
    );
  GET DIAGNOSTICS v_deleted = ROW_COUNT;

  SELECT v_preserved + count(*) INTO v_preserved FROM public.sessions session
  WHERE session.series_id = v_origin.series_id
    AND session.session_date >= CASE WHEN p_scope = 'future' THEN v_origin.session_date ELSE current_date END;
  RETURN jsonb_build_object('deletedCount', v_deleted, 'preservedCount', v_preserved, 'scope', p_scope);
END;
$$;

CREATE OR REPLACE FUNCTION public.duplicate_session_transactional(
  p_session_id integer,
  p_session_date date,
  p_athlete_ids integer[] DEFAULT NULL
) RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO 'public'
AS $$
DECLARE
  v_source public.sessions%ROWTYPE;
  v_new_id integer;
  v_targets integer[];
BEGIN
  SELECT * INTO v_source FROM public.sessions WHERE id = p_session_id;
  IF NOT FOUND OR v_source.club_id <> public.get_my_club_id() THEN RAISE EXCEPTION 'Seance introuvable.'; END IF;
  IF public.get_my_role() NOT IN ('head_coach', 'coach') THEN RAISE EXCEPTION 'Action non autorisee.'; END IF;
  SELECT coalesce(p_athlete_ids, array_agg(athlete_id ORDER BY athlete_id)) INTO v_targets
  FROM public.session_athletes WHERE session_id = p_session_id;
  PERFORM public._assert_session_write(jsonb_build_object(
    'title', v_source.title, 'sessionDate', p_session_date, 'time', v_source.time,
    'durationMinutes', v_source.duration_minutes
  ), v_targets, NULL);

  INSERT INTO public.sessions (
    club_id, title, day, time, type, category, description, instructions, week,
    load_weight, pdf_url, duration_minutes, created_by, session_date,
    training_focus, source_kind, target_group, parent_session_id
  ) VALUES (
    v_source.club_id, v_source.title,
    CASE extract(isodow FROM p_session_date)::integer
      WHEN 1 THEN 'Lundi' WHEN 2 THEN 'Mardi' WHEN 3 THEN 'Mercredi'
      WHEN 4 THEN 'Jeudi' WHEN 5 THEN 'Vendredi' WHEN 6 THEN 'Samedi' ELSE 'Dimanche' END,
    v_source.time, v_source.type, v_source.category, v_source.description,
    v_source.instructions, extract(week FROM p_session_date)::integer,
    v_source.load_weight, v_source.pdf_url, v_source.duration_minutes,
    public.get_my_user_id(), p_session_date, v_source.training_focus,
    'duplicate', v_source.target_group, v_source.id
  ) RETURNING id INTO v_new_id;
  INSERT INTO public.session_athletes (session_id, athlete_id, status)
  SELECT v_new_id, athlete_id, NULL FROM unnest(v_targets) athlete_id;
  RETURN jsonb_build_object('sessionId', v_new_id, 'sourceSessionId', p_session_id);
END;
$$;

CREATE OR REPLACE FUNCTION public.duplicate_week_transactional(
  p_source_monday date,
  p_target_monday date,
  p_athlete_ids integer[] DEFAULT NULL
) RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO 'public'
AS $$
DECLARE
  v_source record;
  v_result jsonb;
  v_ids integer[] := ARRAY[]::integer[];
BEGIN
  IF public.get_my_role() NOT IN ('head_coach', 'coach') THEN RAISE EXCEPTION 'Action non autorisee.'; END IF;
  IF extract(isodow FROM p_source_monday) <> 1 OR extract(isodow FROM p_target_monday) <> 1 THEN
    RAISE EXCEPTION 'Les dates doivent etre des lundis.';
  END IF;
  FOR v_source IN
    SELECT id, session_date FROM public.sessions
    WHERE club_id = public.get_my_club_id()
      AND session_date BETWEEN p_source_monday AND p_source_monday + 6
      AND (p_athlete_ids IS NULL OR EXISTS (
        SELECT 1 FROM public.session_athletes assignment
        WHERE assignment.session_id = sessions.id AND assignment.athlete_id = ANY(p_athlete_ids)
      ))
    ORDER BY session_date, time
  LOOP
    v_result := public.duplicate_session_transactional(
      v_source.id, p_target_monday + (v_source.session_date - p_source_monday), p_athlete_ids
    );
    v_ids := array_append(v_ids, (v_result->>'sessionId')::integer);
  END LOOP;
  RETURN jsonb_build_object('sessionIds', to_jsonb(v_ids), 'duplicatedCount', cardinality(v_ids));
END;
$$;

CREATE OR REPLACE FUNCTION public.save_session_template(p_name text, p_session_id integer)
RETURNS bigint
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO 'public'
AS $$
DECLARE v_id bigint;
