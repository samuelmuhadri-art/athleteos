CREATE OR REPLACE FUNCTION public.refresh_series_group_members(p_series_id bigint, p_from_date date DEFAULT current_date)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO 'public'
AS $$
DECLARE v_series public.session_series%ROWTYPE; v_count integer;
BEGIN
  SELECT * INTO v_series FROM public.session_series WHERE id = p_series_id FOR UPDATE;
  IF NOT FOUND OR v_series.club_id <> public.get_my_club_id() OR v_series.target_group IS NULL THEN
    RAISE EXCEPTION 'Serie de groupe introuvable.';
  END IF;
  IF public.get_my_role() NOT IN ('head_coach', 'coach') THEN RAISE EXCEPTION 'Action non autorisee.'; END IF;
  DELETE FROM public.session_athletes assignment
  USING public.sessions session
  WHERE assignment.session_id = session.id AND session.series_id = p_series_id
    AND session.session_date >= p_from_date
    AND assignment.feedback_submitted_at IS NULL AND assignment.rpe IS NULL AND assignment.comment IS NULL;
  INSERT INTO public.session_athletes (session_id, athlete_id, status)
  SELECT session.id, athlete.id, NULL
  FROM public.sessions session
  JOIN public.athletes athlete ON athlete.club_id = v_series.club_id
    AND athlete.group_name = v_series.target_group
  WHERE session.series_id = p_series_id AND session.session_date >= p_from_date
  ON CONFLICT (session_id, athlete_id) DO NOTHING;
  GET DIAGNOSTICS v_count = ROW_COUNT;
  RETURN jsonb_build_object('seriesId', p_series_id, 'addedAssignments', v_count, 'fromDate', p_from_date);
END;
$$;

