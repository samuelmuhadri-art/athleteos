-- ---------------------------------------------------------------------------
-- Publication en batch : 1 RPC, zéro requête par athlète.
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.publish_session_documents(
  p_session_id integer,
  p_document_ids bigint[],
  p_athlete_ids integer[] DEFAULT NULL,
  p_notification_key text DEFAULT NULL
) RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO 'public'
AS $$
DECLARE
  v_club_id integer := public.get_my_club_id();
  v_user_id integer := public.get_my_user_id();
  v_targets integer[];
  v_new_document_ids bigint[];
  v_visibility text := CASE WHEN p_athlete_ids IS NULL THEN 'all' ELSE 'selected' END;
  v_notification_key text := coalesce(nullif(p_notification_key,''), gen_random_uuid()::text);
  v_associations integer := 0;
BEGIN
  IF v_user_id IS NULL OR public.get_my_role() NOT IN ('head_coach','coach') THEN RAISE EXCEPTION 'Action non autorisee.'; END IF;
  IF NOT EXISTS (SELECT 1 FROM public.sessions session WHERE session.id=p_session_id AND session.club_id=v_club_id) THEN
    RAISE EXCEPTION 'Seance introuvable.';
  END IF;
  -- L'appel représente l'état complet du formulaire : retirer en une seule
  -- écriture les documents désélectionnés, sans supprimer l'objet de la
  -- bibliothèque ni les liens éventuels vers d'autres séances.
  DELETE FROM public.session_documents link
  WHERE link.session_id=p_session_id
    AND NOT (link.document_id=ANY(coalesce(p_document_ids,ARRAY[]::bigint[])));
  IF cardinality(coalesce(p_document_ids, ARRAY[]::bigint[])) = 0 THEN
    RETURN jsonb_build_object('documentCount',0,'recipientCount',0,'associationCount',0);
  END IF;
  IF (SELECT count(DISTINCT id) FROM unnest(p_document_ids) id) <> cardinality(p_document_ids) THEN
    RAISE EXCEPTION 'Un document ne peut etre associe qu une fois.';
  END IF;
  IF EXISTS (SELECT 1 FROM unnest(p_document_ids) id WHERE NOT EXISTS (
    SELECT 1 FROM public.documents document WHERE document.id=id AND document.club_id=v_club_id
  )) THEN RAISE EXCEPTION 'Un document n appartient pas au club.'; END IF;

  SELECT array_agg(assignment.athlete_id ORDER BY assignment.athlete_id) INTO v_targets
  FROM public.session_athletes assignment
  WHERE assignment.session_id=p_session_id
    AND (p_athlete_ids IS NULL OR assignment.athlete_id=ANY(p_athlete_ids));
  IF cardinality(coalesce(v_targets,ARRAY[]::integer[])) = 0 THEN RAISE EXCEPTION 'Aucun destinataire autorise.'; END IF;
  IF p_athlete_ids IS NOT NULL AND cardinality(v_targets) <> (SELECT count(DISTINCT id) FROM unnest(p_athlete_ids) id) THEN
    RAISE EXCEPTION 'Un athlete destinataire n est pas assigne a la seance.';
  END IF;

  SELECT array_agg(id) INTO v_new_document_ids
  FROM unnest(p_document_ids) id
  WHERE NOT EXISTS (SELECT 1 FROM public.session_documents link WHERE link.session_id=p_session_id AND link.document_id=id);

  INSERT INTO public.session_documents (session_id,document_id,visibility,attached_by)
  SELECT p_session_id,id,v_visibility,v_user_id FROM unnest(p_document_ids) id
  ON CONFLICT (session_id,document_id) DO UPDATE SET visibility=EXCLUDED.visibility;

  DELETE FROM public.session_document_recipients recipient
  WHERE recipient.session_id=p_session_id AND recipient.document_id=ANY(p_document_ids);
  IF v_visibility='selected' THEN
    INSERT INTO public.session_document_recipients (session_id,document_id,athlete_id)
    SELECT p_session_id,document_id,athlete_id
    FROM unnest(p_document_ids) document_id CROSS JOIN unnest(v_targets) athlete_id
    ON CONFLICT DO NOTHING;
    GET DIAGNOSTICS v_associations = ROW_COUNT;
  ELSE
    v_associations := cardinality(p_document_ids) * cardinality(v_targets);
  END IF;

  IF cardinality(coalesce(v_new_document_ids,ARRAY[]::bigint[])) > 0 THEN
    INSERT INTO public.athlete_notifications (
      athlete_id,club_id,type,title,description,is_read,session_id,dedupe_key
    )
    SELECT athlete_id,v_club_id,'training_document','Nouveau document d''entraînement disponible',
      CASE WHEN cardinality(v_new_document_ids)=1 THEN 'Un nouveau document est disponible dans ta séance.'
           ELSE cardinality(v_new_document_ids)||' nouveaux documents sont disponibles dans ta séance.' END,
      false,p_session_id,'session-documents-'||p_session_id||'-'||v_notification_key
    FROM unnest(v_targets) athlete_id
    ON CONFLICT (athlete_id,type,dedupe_key) DO NOTHING;
  END IF;
  RETURN jsonb_build_object(
    'documentCount',cardinality(p_document_ids), 'newDocumentCount',cardinality(coalesce(v_new_document_ids,ARRAY[]::bigint[])),
    'recipientCount',cardinality(v_targets), 'associationCount',v_associations,
    'physicalUploadCount',0
  );
END;
$$;

CREATE OR REPLACE FUNCTION public.detach_session_document(p_session_id integer,p_document_id bigint)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path TO 'public' AS $$
BEGIN
  IF public.get_my_role() NOT IN ('head_coach','coach') OR NOT EXISTS (
    SELECT 1 FROM public.sessions session WHERE session.id=p_session_id AND session.club_id=public.get_my_club_id()
  ) THEN RAISE EXCEPTION 'Action non autorisee.'; END IF;
  DELETE FROM public.session_documents WHERE session_id=p_session_id AND document_id=p_document_id;
  RETURN jsonb_build_object('sessionId',p_session_id,'documentId',p_document_id);
END;
$$;

-- Variante structurée : chaque document peut viser tous les athlètes de la
-- séance ou son propre sous-ensemble. Toute la distribution est validée et
-- écrite dans une seule transaction, quel que soit le nombre d'athlètes.
CREATE OR REPLACE FUNCTION public.publish_session_document_distribution(
  p_session_id integer,
  p_distribution jsonb,
  p_notification_key text DEFAULT NULL
) RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO 'public'
AS $$
DECLARE
  v_club_id integer := public.get_my_club_id();
  v_user_id integer := public.get_my_user_id();
  v_items jsonb := coalesce(p_distribution,'[]'::jsonb);
  v_new_document_ids bigint[];
  v_notification_key text := coalesce(nullif(p_notification_key,''),gen_random_uuid()::text);
  v_document_count integer := 0;
  v_recipient_count integer := 0;
  v_association_count integer := 0;
BEGIN
  IF v_user_id IS NULL OR public.get_my_role() NOT IN ('head_coach','coach') THEN
    RAISE EXCEPTION 'Action non autorisee.';
  END IF;
  IF NOT EXISTS (SELECT 1 FROM public.sessions session WHERE session.id=p_session_id AND session.club_id=v_club_id) THEN
    RAISE EXCEPTION 'Seance introuvable.';
  END IF;
  IF jsonb_typeof(v_items) <> 'array' THEN RAISE EXCEPTION 'Distribution documentaire invalide.'; END IF;
  IF EXISTS (
    SELECT 1 FROM jsonb_array_elements(v_items) item
    WHERE jsonb_typeof(item) <> 'object'
      OR nullif(item->>'documentId','') IS NULL
      OR (item ? 'athleteIds' AND jsonb_typeof(item->'athleteIds') NOT IN ('array','null'))
  ) THEN RAISE EXCEPTION 'Distribution documentaire invalide.'; END IF;
  IF (SELECT count(*) FROM jsonb_array_elements(v_items)) <>
     (SELECT count(DISTINCT (item->>'documentId')::bigint) FROM jsonb_array_elements(v_items) item) THEN
    RAISE EXCEPTION 'Un document ne peut etre associe qu une fois.';
  END IF;
  IF EXISTS (
    SELECT 1 FROM jsonb_array_elements(v_items) item
    WHERE NOT EXISTS (
      SELECT 1 FROM public.documents document
      WHERE document.id=(item->>'documentId')::bigint AND document.club_id=v_club_id
    )
  ) THEN RAISE EXCEPTION 'Un document n appartient pas au club.'; END IF;
  IF EXISTS (
    SELECT 1 FROM jsonb_array_elements(v_items) item
    WHERE jsonb_typeof(item->'athleteIds')='array' AND jsonb_array_length(item->'athleteIds')=0
  ) THEN RAISE EXCEPTION 'Un document cible doit avoir au moins un destinataire.'; END IF;
  IF EXISTS (
    SELECT 1
    FROM jsonb_array_elements(v_items) item
    CROSS JOIN LATERAL jsonb_array_elements_text(
      CASE WHEN jsonb_typeof(item->'athleteIds')='array' THEN item->'athleteIds' ELSE '[]'::jsonb END
    ) athlete_id
    WHERE jsonb_typeof(item->'athleteIds')='array'
      AND NOT EXISTS (
        SELECT 1 FROM public.session_athletes assignment
        WHERE assignment.session_id=p_session_id AND assignment.athlete_id=athlete_id::integer
      )
  ) THEN RAISE EXCEPTION 'Un athlete destinataire n est pas assigne a la seance.'; END IF;

  SELECT array_agg((item->>'documentId')::bigint) INTO v_new_document_ids
  FROM jsonb_array_elements(v_items) item
  WHERE NOT EXISTS (
    SELECT 1 FROM public.session_documents link
    WHERE link.session_id=p_session_id AND link.document_id=(item->>'documentId')::bigint
  );

  DELETE FROM public.session_documents link
  WHERE link.session_id=p_session_id
    AND NOT EXISTS (
      SELECT 1 FROM jsonb_array_elements(v_items) item
      WHERE (item->>'documentId')::bigint=link.document_id
    );

  INSERT INTO public.session_documents(session_id,document_id,visibility,attached_by)
  SELECT p_session_id,(item->>'documentId')::bigint,
    CASE WHEN jsonb_typeof(item->'athleteIds')='array' THEN 'selected' ELSE 'all' END,
    v_user_id
  FROM jsonb_array_elements(v_items) item
  ON CONFLICT(session_id,document_id) DO UPDATE SET visibility=EXCLUDED.visibility;

  DELETE FROM public.session_document_recipients recipient WHERE recipient.session_id=p_session_id;
  INSERT INTO public.session_document_recipients(session_id,document_id,athlete_id)
  SELECT p_session_id,(item->>'documentId')::bigint,athlete_id::integer
  FROM jsonb_array_elements(v_items) item
  CROSS JOIN LATERAL jsonb_array_elements_text(
    CASE WHEN jsonb_typeof(item->'athleteIds')='array' THEN item->'athleteIds' ELSE '[]'::jsonb END
  ) athlete_id
  WHERE jsonb_typeof(item->'athleteIds')='array'
  ON CONFLICT DO NOTHING;

  SELECT count(*) INTO v_document_count FROM jsonb_array_elements(v_items);
  SELECT count(DISTINCT assignment.athlete_id),count(*)
    INTO v_recipient_count,v_association_count
  FROM jsonb_array_elements(v_items) item
  JOIN public.session_athletes assignment ON assignment.session_id=p_session_id
    AND (
      coalesce(jsonb_typeof(item->'athleteIds'),'null') <> 'array'
      OR EXISTS (
        SELECT 1 FROM jsonb_array_elements_text(
          CASE WHEN jsonb_typeof(item->'athleteIds')='array' THEN item->'athleteIds' ELSE '[]'::jsonb END
        ) target
        WHERE target::integer=assignment.athlete_id
      )
    );

  IF cardinality(coalesce(v_new_document_ids,ARRAY[]::bigint[])) > 0 THEN
    INSERT INTO public.athlete_notifications(
      athlete_id,club_id,type,title,description,is_read,session_id,dedupe_key
    )
    SELECT DISTINCT assignment.athlete_id,v_club_id,'training_document',
      'Nouveau document d''entraînement disponible',
      CASE WHEN cardinality(v_new_document_ids)=1 THEN 'Un nouveau document est disponible dans ta séance.'
           ELSE cardinality(v_new_document_ids)||' nouveaux documents sont disponibles dans ta séance.' END,
      false,p_session_id,'session-documents-'||p_session_id||'-'||v_notification_key
    FROM jsonb_array_elements(v_items) item
    JOIN public.session_athletes assignment ON assignment.session_id=p_session_id
      AND (
        coalesce(jsonb_typeof(item->'athleteIds'),'null') <> 'array'
        OR EXISTS (
          SELECT 1 FROM jsonb_array_elements_text(
            CASE WHEN jsonb_typeof(item->'athleteIds')='array' THEN item->'athleteIds' ELSE '[]'::jsonb END
          ) target
          WHERE target::integer=assignment.athlete_id
        )
      )
    WHERE (item->>'documentId')::bigint=ANY(v_new_document_ids)
    ON CONFLICT(athlete_id,type,dedupe_key) DO NOTHING;
  END IF;

  RETURN jsonb_build_object(
    'documentCount',v_document_count,
    'newDocumentCount',cardinality(coalesce(v_new_document_ids,ARRAY[]::bigint[])),
    'recipientCount',v_recipient_count,
    'associationCount',v_association_count,
    'physicalUploadCount',0
  );
END;
$$;

CREATE OR REPLACE FUNCTION public.delete_document_transactional(p_document_id bigint)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path TO 'public' AS $$
DECLARE v_document public.documents%ROWTYPE;
BEGIN
  IF public.get_my_role() NOT IN ('head_coach','coach') THEN RAISE EXCEPTION 'Action non autorisee.'; END IF;
  SELECT * INTO v_document FROM public.documents WHERE id=p_document_id AND club_id=public.get_my_club_id() FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'Document introuvable.'; END IF;
  IF EXISTS (SELECT 1 FROM public.session_documents WHERE document_id=p_document_id)
    OR EXISTS (SELECT 1 FROM public.session_template_documents WHERE document_id=p_document_id)
    OR EXISTS (SELECT 1 FROM public.session_series_documents WHERE document_id=p_document_id)
    OR EXISTS (SELECT 1 FROM public.planning_event_documents WHERE document_id=p_document_id) THEN
    RAISE EXCEPTION 'Ce document est encore utilise. Retire d abord ses associations.';
  END IF;
  DELETE FROM public.documents WHERE id=p_document_id;
  RETURN jsonb_build_object('documentId',p_document_id,'storagePath',v_document.storage_path);
END;
$$;

CREATE OR REPLACE FUNCTION public.copy_parent_session_documents()
RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path TO 'public' AS $$
BEGIN
  IF NEW.parent_session_id IS NULL THEN RETURN NEW; END IF;
  INSERT INTO public.session_documents (session_id,document_id,visibility,attached_by)
  SELECT NEW.id,document_id,visibility,NEW.created_by FROM public.session_documents
  WHERE session_id=NEW.parent_session_id ON CONFLICT DO NOTHING;
  INSERT INTO public.session_document_recipients (session_id,document_id,athlete_id)
  SELECT NEW.id,recipient.document_id,recipient.athlete_id
  FROM public.session_document_recipients recipient
  JOIN public.session_athletes assignment ON assignment.session_id=NEW.id AND assignment.athlete_id=recipient.athlete_id
  WHERE recipient.session_id=NEW.parent_session_id ON CONFLICT DO NOTHING;
  RETURN NEW;
END;
$$;
