CREATE OR REPLACE FUNCTION public.save_session_template(p_name text, p_session_id integer)
RETURNS bigint LANGUAGE plpgsql SECURITY DEFINER SET search_path TO 'public' AS $$
DECLARE v_id bigint;
BEGIN
  IF public.get_my_role() NOT IN ('head_coach','coach') THEN RAISE EXCEPTION 'Action non autorisee.'; END IF;
  INSERT INTO public.session_templates (club_id,name,category,type,training_focus,title,duration_minutes,description,instructions,created_by)
  SELECT club_id,btrim(p_name),category,type,training_focus,title,duration_minutes,description,instructions,public.get_my_user_id()
  FROM public.sessions WHERE id=p_session_id AND club_id=public.get_my_club_id()
  ON CONFLICT (club_id,name) DO UPDATE SET category=EXCLUDED.category,type=EXCLUDED.type,
    training_focus=EXCLUDED.training_focus,title=EXCLUDED.title,duration_minutes=EXCLUDED.duration_minutes,
    description=EXCLUDED.description,instructions=EXCLUDED.instructions,updated_at=now()
  RETURNING id INTO v_id;
  IF v_id IS NULL THEN RAISE EXCEPTION 'Seance introuvable.'; END IF;
  DELETE FROM public.session_template_documents WHERE template_id=v_id;
  INSERT INTO public.session_template_documents(template_id,document_id)
  SELECT v_id,document_id FROM public.session_documents WHERE session_id=p_session_id ON CONFLICT DO NOTHING;
  RETURN v_id;
END;
$$;

CREATE OR REPLACE FUNCTION public.create_session_from_template(
  p_template_id bigint,
  p_schedule jsonb,
  p_athlete_ids integer[],
  p_idempotency_key text DEFAULT NULL
) RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path TO 'public' AS $$
DECLARE v_template public.session_templates%ROWTYPE; v_result jsonb; v_document_ids bigint[];
BEGIN
  SELECT * INTO v_template FROM public.session_templates
  WHERE id=p_template_id AND club_id=public.get_my_club_id();
  IF NOT FOUND THEN RAISE EXCEPTION 'Modele introuvable.'; END IF;
  v_result:=public.create_session_with_athletes(jsonb_build_object(
    'title',v_template.title,'category',v_template.category,'type',v_template.type,
    'trainingFocus',v_template.training_focus,'durationMinutes',v_template.duration_minutes,
    'description',v_template.description,'instructions',v_template.instructions
  )||p_schedule,p_athlete_ids,p_idempotency_key);
  UPDATE public.sessions SET source_kind='template' WHERE id=(v_result->>'sessionId')::integer;
  SELECT array_agg(document_id) INTO v_document_ids FROM public.session_template_documents WHERE template_id=p_template_id;
  IF cardinality(coalesce(v_document_ids,ARRAY[]::bigint[]))>0 THEN
    PERFORM public.publish_session_documents((v_result->>'sessionId')::integer,v_document_ids,NULL,p_idempotency_key);
  END IF;
  RETURN v_result||jsonb_build_object('documentCount',cardinality(coalesce(v_document_ids,ARRAY[]::bigint[])));
END;
$$;

CREATE OR REPLACE FUNCTION public.module_key_for_notification_type(p_type text)
RETURNS text LANGUAGE sql IMMUTABLE SET search_path = public, pg_temp AS $$
  SELECT CASE
    WHEN p_type IN ('new_session','session_updated','session_day_reminder','session_response','athlete_session','training_document') THEN 'planning'
    WHEN p_type IN ('session_feedback_reminder','weekly_recap','recap','absence') THEN 'session_feedback'
    WHEN p_type IN ('result_added','goal_achieved','competition_reminder','competition','performance') THEN 'performances'
    WHEN p_type='weekly_report' THEN 'reports'
    WHEN p_type='message' THEN 'messaging'
    WHEN p_type IN ('social_post','social') THEN 'social'
    WHEN p_type IN ('blessure','injury') THEN 'health'
    WHEN p_type='wellness' THEN 'wellness'
    WHEN p_type IN ('charge','load','acwr') THEN 'training_load'
    ELSE NULL END
$$;

