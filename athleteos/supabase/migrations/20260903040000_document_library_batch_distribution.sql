CREATE OR REPLACE FUNCTION public.publish_series_documents(
  p_series_id bigint,
  p_document_ids bigint[],
  p_notification_key text DEFAULT NULL,
  p_from_date date DEFAULT current_date
)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path TO 'public' AS $$
DECLARE
  v_club_id integer:=public.get_my_club_id();
  v_user_id integer:=public.get_my_user_id();
  v_session_ids integer[];
  v_targets integer[];
  v_previous_document_ids bigint[];
  v_new_document_ids bigint[];
  v_occurrence_count integer:=0;
  v_association_count integer:=0;
BEGIN
  IF public.get_my_role() NOT IN ('head_coach','coach') OR NOT EXISTS (
    SELECT 1 FROM public.session_series series WHERE series.id=p_series_id AND series.club_id=v_club_id
  ) THEN RAISE EXCEPTION 'Action non autorisee.'; END IF;
  IF (SELECT count(DISTINCT id) FROM unnest(coalesce(p_document_ids,ARRAY[]::bigint[])) id)
      <> cardinality(coalesce(p_document_ids,ARRAY[]::bigint[])) THEN
    RAISE EXCEPTION 'Un document ne peut etre associe qu une fois.';
  END IF;
  IF EXISTS (SELECT 1 FROM unnest(coalesce(p_document_ids,ARRAY[]::bigint[])) id WHERE NOT EXISTS (
    SELECT 1 FROM public.documents document WHERE document.id=id AND document.club_id=v_club_id
  )) THEN RAISE EXCEPTION 'Un document n appartient pas au club.'; END IF;

  SELECT array_agg(document_id) INTO v_previous_document_ids
  FROM public.session_series_documents WHERE series_id=p_series_id;
  SELECT array_agg(id) INTO v_new_document_ids
  FROM unnest(coalesce(p_document_ids,ARRAY[]::bigint[])) id
  WHERE NOT (id=ANY(coalesce(v_previous_document_ids,ARRAY[]::bigint[])));
  SELECT array_agg(id ORDER BY session_date,id),count(*) INTO v_session_ids,v_occurrence_count
  FROM public.sessions WHERE series_id=p_series_id AND session_date>=coalesce(p_from_date,current_date);

  -- Le formulaire représente l'état complet pour la portée choisie. Les
  -- objets Storage et leurs autres usages ne sont jamais supprimés.
  IF cardinality(coalesce(v_session_ids,ARRAY[]::integer[]))>0
     AND cardinality(coalesce(v_previous_document_ids,ARRAY[]::bigint[]))>0 THEN
    DELETE FROM public.session_documents link
    WHERE link.session_id=ANY(v_session_ids)
      AND link.document_id=ANY(v_previous_document_ids)
      AND NOT (link.document_id=ANY(coalesce(p_document_ids,ARRAY[]::bigint[])));
  END IF;
  DELETE FROM public.session_series_documents WHERE series_id=p_series_id
    AND NOT (document_id=ANY(coalesce(p_document_ids,ARRAY[]::bigint[])));
  INSERT INTO public.session_series_documents(series_id,document_id)
  SELECT p_series_id,id FROM unnest(coalesce(p_document_ids,ARRAY[]::bigint[])) id ON CONFLICT DO NOTHING;
  IF cardinality(coalesce(v_session_ids,ARRAY[]::integer[]))>0 THEN
    INSERT INTO public.session_documents(session_id,document_id,visibility,attached_by)
    SELECT session_id,document_id,'all',v_user_id
    FROM unnest(v_session_ids) session_id
    CROSS JOIN unnest(coalesce(p_document_ids,ARRAY[]::bigint[])) document_id
    ON CONFLICT(session_id,document_id) DO UPDATE SET visibility='all';
    DELETE FROM public.session_document_recipients recipient
    WHERE recipient.session_id=ANY(v_session_ids)
      AND recipient.document_id=ANY(coalesce(p_document_ids,ARRAY[]::bigint[]));
    SELECT array_agg(DISTINCT assignment.athlete_id ORDER BY assignment.athlete_id) INTO v_targets
    FROM public.session_athletes assignment WHERE assignment.session_id=ANY(v_session_ids);
    v_association_count:=v_occurrence_count
      * cardinality(coalesce(p_document_ids,ARRAY[]::bigint[]))
      * cardinality(coalesce(v_targets,ARRAY[]::integer[]));
  END IF;
  IF cardinality(coalesce(v_new_document_ids,ARRAY[]::bigint[]))>0 THEN
    INSERT INTO public.athlete_notifications(athlete_id,club_id,type,title,description,is_read,dedupe_key)
    SELECT athlete_id,v_club_id,'training_document','Nouveau document d''entraînement disponible',
      CASE WHEN cardinality(v_new_document_ids)=1 THEN 'Un nouveau document est disponible dans ta série de séances.'
           ELSE cardinality(v_new_document_ids)||' nouveaux documents sont disponibles dans ta série de séances.' END,
      false,'series-documents-'||p_series_id||'-'||coalesce(nullif(p_notification_key,''),gen_random_uuid()::text)
    FROM unnest(coalesce(v_targets,ARRAY[]::integer[])) athlete_id
    ON CONFLICT (athlete_id,type,dedupe_key) DO NOTHING;
  END IF;
  RETURN jsonb_build_object('seriesId',p_series_id,'occurrenceCount',v_occurrence_count,
    'documentCount',cardinality(coalesce(p_document_ids,ARRAY[]::bigint[])),
    'recipientCount',cardinality(coalesce(v_targets,ARRAY[]::integer[])),
    'associationCount',v_association_count,'physicalUploadCount',0);
END;
$$;

-- Même modèle pour un stage/test/événement : le fichier reste unique dans
-- Storage et tous les liens ainsi que les notifications sont créés en batch.
CREATE OR REPLACE FUNCTION public.publish_planning_event_documents(
  p_event_id bigint,
  p_document_ids bigint[],
  p_notification_key text DEFAULT NULL
) RETURNS jsonb
LANGUAGE plpgsql SECURITY DEFINER SET search_path TO 'public' AS $$
DECLARE
  v_club_id integer := public.get_my_club_id();
  v_targets integer[];
  v_new_document_ids bigint[];
  v_notification_key text := coalesce(nullif(p_notification_key,''), gen_random_uuid()::text);
BEGIN
  IF public.get_my_role() NOT IN ('head_coach','coach') OR NOT EXISTS (
    SELECT 1 FROM public.planning_events event WHERE event.id=p_event_id AND event.club_id=v_club_id
  ) THEN RAISE EXCEPTION 'Action non autorisee.'; END IF;
  IF (SELECT count(DISTINCT id) FROM unnest(coalesce(p_document_ids,ARRAY[]::bigint[])) id)
      <> cardinality(coalesce(p_document_ids,ARRAY[]::bigint[])) THEN
    RAISE EXCEPTION 'Un document ne peut etre associe qu une fois.';
  END IF;
  IF EXISTS (SELECT 1 FROM unnest(coalesce(p_document_ids,ARRAY[]::bigint[])) id WHERE NOT EXISTS (
    SELECT 1 FROM public.documents document WHERE document.id=id AND document.club_id=v_club_id
  )) THEN RAISE EXCEPTION 'Un document n appartient pas au club.'; END IF;

  SELECT array_agg(id) INTO v_new_document_ids
  FROM unnest(coalesce(p_document_ids,ARRAY[]::bigint[])) id
  WHERE NOT EXISTS (
    SELECT 1 FROM public.planning_event_documents link
    WHERE link.event_id=p_event_id AND link.document_id=id
  );

  DELETE FROM public.planning_event_documents link
  WHERE link.event_id=p_event_id
    AND NOT (link.document_id=ANY(coalesce(p_document_ids,ARRAY[]::bigint[])));
  INSERT INTO public.planning_event_documents(event_id,document_id)
  SELECT p_event_id,id FROM unnest(coalesce(p_document_ids,ARRAY[]::bigint[])) id
  ON CONFLICT DO NOTHING;

  SELECT array_agg(assignment.athlete_id ORDER BY assignment.athlete_id) INTO v_targets
  FROM public.planning_event_athletes assignment WHERE assignment.event_id=p_event_id;
  IF cardinality(coalesce(v_new_document_ids,ARRAY[]::bigint[]))>0 THEN
    INSERT INTO public.athlete_notifications(athlete_id,club_id,type,title,description,is_read,dedupe_key)
    SELECT athlete_id,v_club_id,'training_document','Nouveau document d''entraînement disponible',
      CASE WHEN cardinality(v_new_document_ids)=1 THEN 'Un nouveau document est disponible dans ton événement.'
           ELSE cardinality(v_new_document_ids)||' nouveaux documents sont disponibles dans ton événement.' END,
      false,'event-documents-'||p_event_id||'-'||v_notification_key
    FROM unnest(coalesce(v_targets,ARRAY[]::integer[])) athlete_id
    ON CONFLICT (athlete_id,type,dedupe_key) DO NOTHING;
  END IF;
  RETURN jsonb_build_object(
    'eventId',p_event_id,
    'documentCount',cardinality(coalesce(p_document_ids,ARRAY[]::bigint[])),
    'newDocumentCount',cardinality(coalesce(v_new_document_ids,ARRAY[]::bigint[])),
    'recipientCount',cardinality(coalesce(v_targets,ARRAY[]::integer[])),
    'physicalUploadCount',0
  );
END;
$$;

