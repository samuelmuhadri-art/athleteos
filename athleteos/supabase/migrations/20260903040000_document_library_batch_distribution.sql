-- Enregistrement atomique des métadonnées après l'upload. Le client ne doit
-- pas dépendre d'un INSERT ... RETURNING soumis à la policy SELECT avant que
-- le document ne soit lié à une séance.
CREATE OR REPLACE FUNCTION public.register_training_document(
  p_name text,
  p_storage_path text,
  p_mime_type text,
  p_size_bytes bigint,
  p_category text DEFAULT NULL,
  p_tags text[] DEFAULT ARRAY[]::text[]
) RETURNS jsonb
LANGUAGE plpgsql SECURITY DEFINER SET search_path TO 'public' AS $$
DECLARE v_document public.documents%ROWTYPE; v_club_id integer:=public.get_my_club_id();
BEGIN
  IF public.get_my_role() NOT IN ('head_coach','coach') THEN RAISE EXCEPTION 'Action non autorisee.'; END IF;
  IF split_part(p_storage_path,'/',1) <> v_club_id::text THEN RAISE EXCEPTION 'Chemin Storage invalide.'; END IF;
  INSERT INTO public.documents (club_id,name,storage_path,mime_type,size_bytes,category,tags,uploaded_by)
  VALUES (v_club_id,btrim(p_name),p_storage_path,p_mime_type,p_size_bytes,nullif(p_category,''),coalesce(p_tags,ARRAY[]::text[]),public.get_my_user_id())
  RETURNING * INTO v_document;
  RETURN to_jsonb(v_document);
END;
$$;

