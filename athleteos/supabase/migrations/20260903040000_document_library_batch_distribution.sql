-- ---------------------------------------------------------------------------
-- Un objet Storage unique, réutilisé par autant de séances et destinataires
-- que nécessaire. Les chemins restent dans le bucket privé historique afin
-- de conserver toute la validation/signature déjà en place.
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.documents (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  club_id integer NOT NULL REFERENCES public.clubs(id) ON DELETE CASCADE,
  name text NOT NULL,
  storage_path text NOT NULL,
  mime_type text NOT NULL,
  size_bytes bigint NOT NULL DEFAULT 0,
  category text,
  tags text[] NOT NULL DEFAULT ARRAY[]::text[],
  uploaded_by integer REFERENCES public.users(id) ON DELETE SET NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (club_id, storage_path),
  CONSTRAINT documents_name_check CHECK (char_length(btrim(name)) BETWEEN 1 AND 255),
  CONSTRAINT documents_size_check CHECK (size_bytes BETWEEN 0 AND 31457280)
);

CREATE TABLE IF NOT EXISTS public.session_documents (
  session_id integer NOT NULL REFERENCES public.sessions(id) ON DELETE CASCADE,
  document_id bigint NOT NULL REFERENCES public.documents(id) ON DELETE RESTRICT,
  visibility text NOT NULL DEFAULT 'all',
  attached_by integer REFERENCES public.users(id) ON DELETE SET NULL,
  attached_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (session_id, document_id),
  CONSTRAINT session_documents_visibility_check CHECK (visibility IN ('all', 'selected'))
);

CREATE TABLE IF NOT EXISTS public.session_document_recipients (
  session_id integer NOT NULL,
  document_id bigint NOT NULL,
  athlete_id integer NOT NULL REFERENCES public.athletes(id) ON DELETE CASCADE,
  created_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (session_id, document_id, athlete_id),
  FOREIGN KEY (session_id, document_id)
    REFERENCES public.session_documents(session_id, document_id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS public.session_template_documents (
  template_id bigint NOT NULL REFERENCES public.session_templates(id) ON DELETE CASCADE,
  document_id bigint NOT NULL REFERENCES public.documents(id) ON DELETE RESTRICT,
  PRIMARY KEY (template_id, document_id)
);

CREATE TABLE IF NOT EXISTS public.session_series_documents (
  series_id bigint NOT NULL REFERENCES public.session_series(id) ON DELETE CASCADE,
  document_id bigint NOT NULL REFERENCES public.documents(id) ON DELETE RESTRICT,
  PRIMARY KEY (series_id, document_id)
);

CREATE TABLE IF NOT EXISTS public.planning_event_documents (
  event_id bigint NOT NULL REFERENCES public.planning_events(id) ON DELETE CASCADE,
  document_id bigint NOT NULL REFERENCES public.documents(id) ON DELETE RESTRICT,
  PRIMARY KEY (event_id, document_id)
);

CREATE INDEX IF NOT EXISTS documents_club_category_name_idx
  ON public.documents (club_id, category, lower(name));
CREATE INDEX IF NOT EXISTS session_documents_document_idx
  ON public.session_documents (document_id, session_id);
CREATE INDEX IF NOT EXISTS session_document_recipients_athlete_idx
  ON public.session_document_recipients (athlete_id, session_id, document_id);

-- Les anciens pdf_url deviennent des entrées de bibliothèque et des liens de
-- séance, sans déplacement ni duplication de l'objet Storage.
INSERT INTO public.documents (club_id, name, storage_path, mime_type, size_bytes, uploaded_by, created_at)
SELECT DISTINCT ON (session.club_id, session.pdf_url)
  session.club_id,
  coalesce(nullif(regexp_replace(session.pdf_url, '^.*/', ''), ''), 'Document historique'),
  session.pdf_url,
  'application/octet-stream',
  0,
  session.created_by,
  now()
FROM public.sessions session
WHERE nullif(session.pdf_url, '') IS NOT NULL
ON CONFLICT (club_id, storage_path) DO NOTHING;

INSERT INTO public.session_documents (session_id, document_id, visibility, attached_by)
SELECT session.id, document.id, 'all', session.created_by
FROM public.sessions session
JOIN public.documents document
  ON document.club_id = session.club_id AND document.storage_path = session.pdf_url
WHERE nullif(session.pdf_url, '') IS NOT NULL
ON CONFLICT (session_id, document_id) DO NOTHING;

-- ---------------------------------------------------------------------------
-- Autorisations : le staff voit la bibliothèque du club. Un athlète ne voit
-- qu'un document lié à une séance/événement auquel il est réellement affecté.
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.can_access_training_document(p_document_id bigint)
RETURNS boolean
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path TO 'public'
AS $$
  SELECT EXISTS (
    SELECT 1 FROM public.documents document
    WHERE document.id = p_document_id
      AND document.club_id = public.get_my_club_id()
      AND (
        public.get_my_role() IN ('head_coach', 'coach')
        OR EXISTS (
          SELECT 1
          FROM public.session_documents link
          JOIN public.session_athletes assignment ON assignment.session_id = link.session_id
          WHERE link.document_id = document.id
            AND assignment.athlete_id = public.get_my_athlete_id()
            AND (
              link.visibility = 'all'
              OR EXISTS (
                SELECT 1 FROM public.session_document_recipients recipient
                WHERE recipient.session_id = link.session_id
                  AND recipient.document_id = link.document_id
                  AND recipient.athlete_id = assignment.athlete_id
              )
            )
        )
        OR EXISTS (
          SELECT 1
          FROM public.planning_event_documents link
          JOIN public.planning_event_athletes assignment ON assignment.event_id = link.event_id
          WHERE link.document_id = document.id
            AND assignment.athlete_id = public.get_my_athlete_id()
        )
      )
  )
$$;

CREATE OR REPLACE FUNCTION public.can_access_training_document_path(p_storage_path text)
RETURNS boolean
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path TO 'public'
AS $$
  SELECT
    EXISTS (
      SELECT 1 FROM public.documents document
      WHERE document.storage_path = p_storage_path
        AND public.can_access_training_document(document.id)
    )
    OR EXISTS (
      SELECT 1
      FROM public.sessions session
      JOIN public.session_athletes assignment ON assignment.session_id = session.id
      WHERE session.pdf_url = p_storage_path
        AND session.club_id = public.get_my_club_id()
        AND (
          public.get_my_role() IN ('head_coach', 'coach')
          OR assignment.athlete_id = public.get_my_athlete_id()
        )
    )
$$;

CREATE OR REPLACE FUNCTION public.can_access_session_document_link(p_session_id integer,p_document_id bigint)
RETURNS boolean LANGUAGE sql STABLE SECURITY DEFINER SET search_path TO 'public' AS $$
  SELECT EXISTS (
    SELECT 1
    FROM public.session_documents link
    JOIN public.sessions session ON session.id=link.session_id
    WHERE link.session_id=p_session_id AND link.document_id=p_document_id
      AND session.club_id=public.get_my_club_id()
      AND (
        public.get_my_role() IN ('head_coach','coach')
        OR EXISTS (
          SELECT 1 FROM public.session_athletes assignment
          WHERE assignment.session_id=link.session_id
            AND assignment.athlete_id=public.get_my_athlete_id()
            AND (
              link.visibility='all'
              OR EXISTS (
                SELECT 1 FROM public.session_document_recipients recipient
                WHERE recipient.session_id=link.session_id
                  AND recipient.document_id=link.document_id
                  AND recipient.athlete_id=assignment.athlete_id
              )
            )
        )
      )
  )
$$;

CREATE OR REPLACE FUNCTION public.can_access_planning_event_document_link(p_event_id bigint,p_document_id bigint)
RETURNS boolean LANGUAGE sql STABLE SECURITY DEFINER SET search_path TO 'public' AS $$
  SELECT EXISTS (
    SELECT 1
    FROM public.planning_event_documents link
    JOIN public.planning_events event ON event.id=link.event_id
    WHERE link.event_id=p_event_id AND link.document_id=p_document_id
      AND event.club_id=public.get_my_club_id()
      AND (
        public.get_my_role() IN ('head_coach','coach')
        OR EXISTS (
          SELECT 1 FROM public.planning_event_athletes assignment
          WHERE assignment.event_id=link.event_id AND assignment.athlete_id=public.get_my_athlete_id()
        )
      )
  )
$$;

